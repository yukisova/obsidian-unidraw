const dictionaries: Record<Language, Record<MessageKey, string>> = { en, zh };

export function detectLanguage(): Language {
  try {
    const stored = window.localStorage.getItem("language");
    if (stored) return stored.toLowerCase().startsWith("zh") ? "zh" : "en";
  } catch {
    /* localStorage can be unavailable in some sandboxes. */
  }
  const lang = (document.documentElement.lang || navigator.language || "en").toLowerCase();
  return lang.startsWith("zh") ? "zh" : "en";
}

export function resolveLanguage(setting: LanguageSetting | undefined): Language {
  if (setting === "en" || setting === "zh") return setting;
  return detectLanguage();
}

export type Translator = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function createTranslator(language: Language): Translator {
  return (key, vars) => {
    const dict = dictionaries[language] ?? en;
    let text = dict[key] ?? en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replace(new RegExp(`\\{${name}\\}`, "g"), String(value));
      }
    }
    return text;
  };
}
